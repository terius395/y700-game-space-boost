# Shared helpers, sourced by service.sh, uninstall.sh and bin/*.sh.
# Expects MODDIR to be set by the caller.

PP_PKG=com.zui.pp
TA_PKG=com.zui.tassistent
PP_DATA=/data/user/0/com.zui.pp/files/performanceconfig.xml
PP_GAME_DATA=/data/user/0/com.zui.pp/files/game_policy.xml
SYS_PERF=/system/etc/performanceconfig.xml
MOD_PERF="$MODDIR/system/etc/performanceconfig.xml"
MOD_GAME="$MODDIR/system/etc/game_policy.xml"
STOCK_PERF="$MODDIR/stock/performanceconfig.xml"
STOCK_GAME="$MODDIR/stock/game_policy.xml"
MARKER='generated by y700-perf-tuner'
LOG="$MODDIR/tuner.log"
STAGED=/data/adb/modules_update/y700_perf_tuner

log() {
  echo "$(date '+%m-%d %H:%M:%S') $*" >> "$LOG"
}

file_md5() {
  md5sum "$1" 2>/dev/null | cut -d' ' -f1
}

xml_version() {
  sed -nE 's/.*<(PerformanceConfig|AppPolicy)[^>]*version *= *"([0-9]*)".*/\2/p' "$1" 2>/dev/null | head -n1
}

# com.zui.pp is persistent; the system restarts it right away and it reloads the config.
# com.zui.tassistent (which applies the limits) has to be reset as well: its
# onServiceConnected clears its pending callback list after the first registration,
# so after a com.zui.pp restart it never re-registers and keeps the old limits.
# Stop its service instead of killing the process: onDestroy releases its perflocks,
# while a killed client leaves them in the perf HAL until reboot. com.zui.pp starts
# the service again on the next game launch.
restart_pp() {
  ta="not running"
  if dumpsys activity services $TA_PKG 2>/dev/null | grep -q "$TA_PKG/.GameService"; then
    am stopservice -n $TA_PKG/.GameService >/dev/null 2>&1 && ta="service stopped"
    sleep 1
  fi
  pid=$(pidof $PP_PKG)
  [ -n "$pid" ] && kill $pid
  log "restarted $PP_PKG (old pid ${pid:-none}), $TA_PKG: $ta"
}

# Overwrite the copy com.zui.pp actually loads. Writing through cat keeps the
# file's owner, mode and SELinux label.
# A tuned copy is made immutable: Lenovo cloud updates compare their version with
# /system/etc (stock, lower) and would otherwise replace it. On Magica late-load
# root the module's system/ overlay is never mounted, and a manual bind mount
# would show up in every app's mountinfo, so the immutable flag is used instead.
# com.zui.pp catches the failed cloud copy.
# write_locked <src> <dst> <pattern the src must contain>
write_locked() {
  [ -f "$2" ] || return 1
  # never hand com.zui.pp an empty or foreign file
  grep -q "$3" "$1" 2>/dev/null || return 1
  chattr -i "$2" 2>/dev/null
  cat "$1" > "$2" || return 1
  grep -q "$MARKER" "$2" && chattr +i "$2" 2>/dev/null
  return 0
}

# com.zui.pp keeps its configs in credential-encrypted storage, which stays locked
# after boot until the first unlock on devices with a screen lock. Waits up to
# $1 seconds (default 600) for the data copy to become readable.
wait_pp_data() {
  n=0
  while [ ! -f "$PP_DATA" ] && [ $n -lt "${1:-600}" ]; do
    sleep 5
    n=$((n + 5))
  done
  [ -f "$PP_DATA" ]
}

write_pp_data() { write_locked "$1" "$PP_DATA" '<GameLimitConfig>'; }
write_pp_game() { write_locked "$1" "$PP_GAME_DATA" '<AppList'; }

# An update that is installed but not rebooted yet replaces this module dir at
# boot. Copy the user's current tuning into it so an Apply is not lost.
mirror_to_staged() {
  [ -d "$STAGED" ] || return 0
  mkdir -p "$STAGED/system/etc"
  for f in system/etc/performanceconfig.xml system/etc/game_policy.xml tuning.json; do
    if [ -f "$MODDIR/$f" ]; then
      cp -f "$MODDIR/$f" "$STAGED/$f"
    else
      rm -f "$STAGED/$f"
    fi
  done
  log "mirrored tuning to pending update"
}

# Re-apply the immutable flag if something cleared it.
protect_pp_data() {
  for f in "$PP_DATA" "$PP_GAME_DATA"; do
    grep -q "$MARKER" "$f" 2>/dev/null || continue
    lsattr "$f" 2>/dev/null | cut -d' ' -f1 | grep -q i || chattr +i "$f"
  done
}

# Make the data copies match the generated files. game_policy.xml is only
# generated for the Beast memory boost; without it the stock copy goes back.
# Returns 0 when anything changed.
sync_pp_data() {
  changed=1
  if [ -f "$MOD_PERF" ] && grep -q "$MARKER" "$MOD_PERF" &&
     [ "$(file_md5 "$MOD_PERF")" != "$(file_md5 "$PP_DATA")" ] && write_pp_data "$MOD_PERF"; then
    log "synced $PP_DATA to version $(xml_version "$MOD_PERF")"
    changed=0
  fi
  if [ -f "$MOD_GAME" ] && grep -q "$MARKER" "$MOD_GAME"; then
    if [ "$(file_md5 "$MOD_GAME")" != "$(file_md5 "$PP_GAME_DATA")" ] && write_pp_game "$MOD_GAME"; then
      log "synced $PP_GAME_DATA to version $(xml_version "$MOD_GAME")"
      changed=0
    fi
  elif grep -q "$MARKER" "$PP_GAME_DATA" 2>/dev/null && write_pp_game "$STOCK_GAME"; then
    log "restored stock $PP_GAME_DATA"
    changed=0
  fi
  return $changed
}
