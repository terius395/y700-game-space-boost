# KernelSU / Magisk installer hook. Runs with MODPATH pointing at the new module dir.

SYS_PERF=/system/etc/performanceconfig.xml
SYS_GAME=/system/etc/game_policy.xml
MARKER='generated by y700-perf-tuner'
OLD=/data/adb/modules/y700_perf_tuner

model=$(getprop ro.product.model)
# Needs the ZUI performance stack this module drives (com.zui.pp + its configs).
[ -f "$SYS_PERF" ] && [ -f "$SYS_GAME" ] || abort "! ZUI performance configs not found in /system/etc"
grep -q '<GameLimitConfig>' "$SYS_PERF" || abort "! $SYS_PERF has no GameLimitConfig section"
pm path com.zui.pp >/dev/null 2>&1 || abort "! com.zui.pp (ZUI Performance) is not installed"
if [ "$model" != "TB322FC" ]; then
  ui_print "! $model is not verified (verified: Legion Y700 Gen4 TB322FC)."
  ui_print "! Frequencies are read from this device; check them in game after saving."
fi
[ -f /data/user/0/com.zui.pp/files/performanceconfig.xml ] || ui_print "- com.zui.pp has no data copy yet, it will be created on boot"

mkdir -p "$MODPATH/stock"

# Stock source: the running system unless it is already our overlay, then the
# previous install. The zip also ships the stock file it was generated from.
if ! grep -q "$MARKER" "$SYS_PERF"; then
  cp -f "$SYS_PERF" "$MODPATH/stock/performanceconfig.xml"
elif [ -f "$OLD/stock/performanceconfig.xml" ]; then
  cp -f "$OLD/stock/performanceconfig.xml" "$MODPATH/stock/performanceconfig.xml"
fi
if ! grep -q "$MARKER" "$SYS_GAME"; then
  cp -f "$SYS_GAME" "$MODPATH/stock/game_policy.xml"
elif [ -f "$OLD/stock/game_policy.xml" ]; then
  cp -f "$OLD/stock/game_policy.xml" "$MODPATH/stock/game_policy.xml"
fi

stock_md5=$(md5sum "$MODPATH/stock/performanceconfig.xml" | cut -d' ' -f1)
built_md5=$(cat "$MODPATH/stock.md5" 2>/dev/null)

if [ -f "$OLD/module.prop" ]; then
  # Update: keep exactly what the user had, including "stock" (no tuning saved).
  rm -rf "$MODPATH/system" "$MODPATH/tuning.json"
  [ -f "$OLD/tuning.json" ] && cp -f "$OLD/tuning.json" "$MODPATH/tuning.json"
  old_stock_md5=$(md5sum "$OLD/stock/performanceconfig.xml" 2>/dev/null | cut -d' ' -f1)
  if [ "$old_stock_md5" = "$stock_md5" ]; then
    [ -d "$OLD/system/etc" ] && mkdir -p "$MODPATH/system" && cp -rf "$OLD/system/etc" "$MODPATH/system/"
    ui_print "- Kept previous settings"
  elif [ -f "$MODPATH/tuning.json" ]; then
    # Saved tuning was generated from the old firmware's config.
    ui_print "! Firmware config changed: open the module WebUI and press Save to regenerate."
  fi
elif [ "$stock_md5" != "$built_md5" ]; then
  # The bundled file was generated from a different firmware's config. Do not
  # overlay it; the WebUI generates one from this device's stock copy.
  rm -rf "$MODPATH/system" "$MODPATH/tuning.json"
  ui_print "! Firmware config differs from the one this zip was built for."
  ui_print "! Open the module WebUI, pick your limits and press Save."
else
  ui_print "- Tuned config version $(sed -n 's/.*version *= *"\([0-9]*\)".*/\1/p' "$MODPATH/system/etc/performanceconfig.xml" | head -n1)"
fi

set_perm_recursive "$MODPATH" 0 0 0755 0644
set_perm_recursive "$MODPATH/bin" 0 0 0755 0755
ui_print "- Reboot, then pick a mode in Game Assistant as usual"
