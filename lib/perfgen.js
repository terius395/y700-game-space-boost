/*
 * perfgen.js - rewrites ZUI com.zui.pp performanceconfig.xml so the Game Assistant
 * performance modes (Balance / PowerSave / Beast) use custom CPU/GPU limits.
 *
 * How the stock data is laid out (Legion Y700 Gen4, Kirby-PRC):
 *   game_policy.xml   <App pkg=...><Attribute name="LimitConfig">
 *                       "<balance> <powersave> <beast>" (space separated)
 *                       each mode: "temp:id_id_id_id_id|temp:id_..." (one entry per thermal tier)
 *   performanceconfig.xml <GameLimitConfig><Type name="BigCore|MegaCore|GPU|...">
 *                       <Freq level="id">max_min_boost</Freq>
 *                       CPU values in kHz, GPU values are kgsl pwrlevel indexes (0 = fastest), -1 = no limit
 *
 * com.zui.pp turns the selected mode's tiers into JSON and com.zui.tassistent applies
 * them with perfLockAcquire, picking the tier by temperature.
 *
 * Works in Node (module.exports) and in a browser / KernelSU WebUI (window.PerfGen).
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.PerfGen = factory();
  }
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const MODES = ['balance', 'powersave', 'beast'];

  // Defaults for TB322FC (SM8750P), used by the CLI build. The WebUI reads the real
  // tables from sysfs (detectTables) and passes them in config.tables.
  const DEFAULT_TABLES = {
    // policy0, cpu0-5
    BigCore: [384000, 556800, 748800, 960000, 1152000, 1363200, 1555200, 1785600, 1996800,
      2227200, 2400000, 2745600, 2918400, 3072000, 3321600, 3532800],
    // policy6, cpu6-7
    MegaCore: [1017600, 1209600, 1401600, 1689600, 1958400, 2246400, 2438400, 2649600, 2841600,
      3072000, 3283200, 3513600, 3801600, 4089600, 4204800, 4320000],
    // kgsl pwrlevel index -> MHz
    GPU: [1100, 1050, 967, 900, 832, 734, 660, 607, 525, 443, 389, 342, 222, 160],
  };

  // config field prefix -> Type name in performanceconfig.xml
  const CPU_FIELDS = { little: 'LittleCore', big: 'BigCore', titan: 'TitanCore', mega: 'MegaCore' };

  // Lenovo names cpufreq clusters by count, lowest CPUs first. Matches the TB322FC
  // perflock mapping (BigCore = policy0, MegaCore = policy6).
  const CLUSTER_TYPES = {
    1: ['BigCore'],
    2: ['BigCore', 'MegaCore'],
    3: ['LittleCore', 'BigCore', 'MegaCore'],
    4: ['LittleCore', 'BigCore', 'TitanCore', 'MegaCore'],
  };

  /**
   * Build frequency tables from sysfs readings.
   * @param {Array<{policy:string, cpus:number[], freqs:number[]}>} policies cpufreq policies (kHz)
   * @param {number[]} gpuHz kgsl gpu_available_frequencies, in pwrlevel order
   * @returns {{ tables: object, clusters: Array }|null} null when the layout is unknown
   */
  function detectTables(policies, gpuHz) {
    const sorted = policies.filter((p) => p.freqs.length).sort((a, b) => a.cpus[0] - b.cpus[0]);
    const types = CLUSTER_TYPES[sorted.length];
    if (!types || !gpuHz.length) return null;
    const tables = { GPU: gpuHz.map((hz) => Math.round(hz / 1e6)) };
    const clusters = sorted.map((p, i) => {
      const freqs = p.freqs.slice().sort((a, b) => a - b);
      tables[types[i]] = freqs;
      return { type: types[i], policy: p.policy, cores: p.cpus.length, max: freqs[freqs.length - 1] };
    });
    return { tables, clusters };
  }

  const GENERATED_MARKER = 'generated by y700-perf-tuner';

  // Special perflock items added to <PerformanceSpecialList>. com.zui.pp acquires the
  // item named in SpecialBoostConfig when Beast (3rd) / Balance (1st) is selected,
  // releasing its previous lock first. Only MIN opcodes from Lenovo's own "Full"
  // profile are used, so nothing here can cap a bus below its default.
  const BEAST_BOOST_ITEM = 'Y700BeastBoost';
  const RELEASE_ITEM = 'Y700Release';
  const BEAST_BOOST_OPCODES = [
    ['0x43488000', 2092000, 'DDR_LAT_MINFREQ_GOLD'],
    ['0x4348C000', 1066000, 'LLCC_MEMLAT_MIN_FREQ_GOLD'],
    ['0x4345C000', 600000, 'LLCC_MEMLAT_MIN_FREQ_SILVER'],
    ['0x43458000', 2035200, 'L3_MEMLAT_MIN_FREQ_PRIME'],
    ['0x43480000', 2035200, 'L3_MEMLAT_MIN_FREQ_GOLD'],
    ['0x40CAC000', 100, 'SCHED_UCLAMP_BOOST'],
  ];

  function stripComments(xml) {
    return xml.replace(/<!--[\s\S]*?-->/g, '');
  }

  /** Parse game_policy.xml into [{ pkg, modes: [[{ temp, ids: [] }]] }]. */
  function parseGamePolicy(gameXml) {
    const apps = [];
    const body = stripComments(gameXml);
    for (const m of body.matchAll(/<App\s+name="([^"]*)"\s+pkg="([^"]*)">([\s\S]*?)<\/App>/g)) {
      const limit = /<Attribute name="LimitConfig">([\s\S]*?)<\/Attribute>/.exec(m[3]);
      if (!limit) continue;
      const modes = limit[1].trim().split(/\s+/).map((group) =>
        group.split('|').map((tier) => {
          const [temp, ids] = tier.split(':');
          return { temp, ids: ids ? ids.split('_') : [] };
        }).filter((tier) => tier.ids.length > 0));
      apps.push({ name: m[1], pkg: m[2], modes });
    }
    return apps;
  }

  /** Parse <GameLimitConfig> Freq tables: { Type: { id: [max, min, boost] } } plus type order. */
  function parseLimitTables(perfXml) {
    const section = /<GameLimitConfig>([\s\S]*?)<\/GameLimitConfig>/.exec(stripComments(perfXml));
    if (!section) throw new Error('GameLimitConfig section not found');
    const tables = {};
    const order = [];
    for (const t of section[1].matchAll(/<Type name\s*=\s*"([^"]+)">([\s\S]*?)<\/Type>/g)) {
      const name = t[1];
      if (name === 'TempLevel') continue;
      order.push(name);
      tables[name] = {};
      for (const f of t[2].matchAll(/<Freq level\s*=\s*"([^"]+)">([^<]*)<\/Freq>/g)) {
        tables[name][f[1]] = f[2].trim().split('_').map(Number);
      }
    }
    return { tables, order };
  }

  function snapFloor(table, value) {
    let best = table[0];
    for (const f of table) {
      if (f <= value) best = f;
    }
    return best;
  }

  function gpuLevelForMhz(table, mhz) {
    // fastest level whose frequency does not exceed the request
    for (let i = 0; i < table.length; i++) {
      if (table[i] <= mhz) return i;
    }
    return table.length - 1;
  }

  function isSet(v) {
    return v !== undefined && v !== null && v !== '' && Number(v) >= 0;
  }

  /**
   * Compute the new [max, min, boost] triple for a CPU cluster entry.
   * The mode's first (coolest) tier takes the configured value; hotter tiers keep
   * their stock ratio to it so the thermal step-down still happens.
   */
  function scaleCpu(stock, stockBase, newBase, table, scaleHotTiers, isBaseTier) {
    const out = stock.slice();
    for (const idx of [0, 1]) {
      const target = newBase[idx];
      if (target === null) continue;
      if (isBaseTier) {
        out[idx] = target;
      } else if (scaleHotTiers && stock[idx] > 0 && stockBase[idx] > 0) {
        out[idx] = Math.min(target, snapFloor(table, stock[idx] * target / stockBase[idx]));
      } else if (stock[idx] > target || (idx === 0 && stock[idx] < 0)) {
        // never let a hotter tier exceed the new base tier; an unlimited (-1) max
        // would, while an unset (-1) min is already below it
        out[idx] = target;
      }
    }
    if (out[0] > 0 && out[1] > out[0]) out[1] = out[0];
    // boost pins max=min=boost during heavy game scenes (TGPA). Keep it in step with
    // the new max: never below a raised cap, never above a lowered one.
    if (stock[2] > 0 && out[0] > 0) {
      if (stock[2] === stock[0]) out[2] = out[0];
      else if (out[0] >= stock[0]) out[2] = Math.max(stock[2], out[0]);
      else out[2] = Math.min(stock[2], out[0]);
    }
    return out;
  }

  function scaleGpu(stock, stockBase, newBase, maxLevel, scaleHotTiers, isBaseTier) {
    const out = stock.slice();
    for (const idx of [0, 1]) {
      const target = newBase[idx];
      if (target === null) continue;
      if (isBaseTier) {
        out[idx] = target;
      } else if (scaleHotTiers && stock[idx] >= 0 && stockBase[idx] >= 0) {
        out[idx] = Math.min(maxLevel, Math.max(target, stock[idx] + (target - stockBase[idx])));
      } else if (idx === 0 ? stock[idx] < target : stock[idx] >= 0 && stock[idx] < target) {
        // pwrlevel indexes: smaller is faster. A hotter tier may not be faster than the
        // base tier; an unset (-1) min level means no floor and stays that way.
        out[idx] = target;
      }
    }
    // pwrlevel: min level index must be >= max level index (slower or equal)
    if (out[0] >= 0 && out[1] >= 0 && out[1] < out[0]) out[1] = out[0];
    return out;
  }

  function specialItemsXml() {
    const lines = ['        <!-- ' + GENERATED_MARKER + ': Beast memory floors + uclamp -->'];
    lines.push('        <Item name = "' + BEAST_BOOST_ITEM + '">');
    BEAST_BOOST_OPCODES.forEach(([code, param, name]) =>
      lines.push('            <PerfLockConfig code = "' + code + '" param = "' + param + '"/><!--' + name + '-->'));
    lines.push('        </Item>');
    // Balance has no boost of its own for most games; acquiring this releases the Beast lock.
    lines.push('        <Item name = "' + RELEASE_ITEM + '">');
    lines.push('            <PerfLockConfig code = "0x40CAC000" param = "0"/><!--SCHED_UCLAMP_BOOST off-->');
    lines.push('        </Item>');
    return lines.join('\n');
  }

  /** Point every game's Beast boost at BEAST_BOOST_ITEM and Balance "NoBoost" at RELEASE_ITEM. */
  function rewriteGamePolicy(gameXml, version) {
    let changed = 0;
    let xml = gameXml.replace(/(<Attribute name="SpecialBoostConfig">)([^<]*)(<\/Attribute>)/g, (all, open, value, close) => {
      const parts = value.trim().split(/\s+/);
      if (parts.length < 3) return all;
      if (parts[0] === 'NoBoost') parts[0] = RELEASE_ITEM;
      parts[2] = BEAST_BOOST_ITEM;
      changed++;
      return open + parts.join(' ') + close;
    });
    xml = xml.replace(/(<AppPolicy\b[^>]*\bversion\s*=\s*")[^"]*(")/, '$1' + version + '$2');
    xml = xml.replace(/(<\?xml[^>]*\?>)/, '$1\n<!-- ' + GENERATED_MARKER + ' -->');
    return { xml, changed };
  }

  function resolveVersion(version) {
    if (version && version !== 'auto') return String(version);
    // 29 + yyMMddHHmm: far above stock (2024xxxx) so neither the startup copy
    // nor cloud updates replace it, and strictly increasing between applies.
    const d = new Date();
    const p = (n) => String(n).padStart(2, '0');
    return '29' + p(d.getFullYear() % 100) + p(d.getMonth() + 1) + p(d.getDate()) + p(d.getHours()) + p(d.getMinutes());
  }

  /**
   * @param {string} perfXml  stock performanceconfig.xml
   * @param {string} gameXml  stock game_policy.xml
   * @param {object} config   { version, scaleHotTiers, modes: { balance: { bigMax, bigMin, megaMax, megaMin, gpuMaxMhz, gpuMinMhz, lock } } }
   *                          lock: true copies the coolest tier into every hotter tier (no thermal step-down)
   *                          beast.memBoost: true adds DDR/LLCC/L3 floors + uclamp boost to Beast
   * @returns {{ xml: string, gameXml: string|null, version: string, changes: Array, stats: object }}
   *          gameXml is the rewritten game_policy.xml, or null when it must stay stock
   */
  function generate(perfXml, gameXml, config) {
    if (perfXml.includes(GENERATED_MARKER) || gameXml.includes(GENERATED_MARKER)) {
      throw new Error('input is already generated; pass the stock files');
    }
    const cfg = config || {};
    const tables = Object.assign({}, DEFAULT_TABLES, cfg.tables || {});
    const scaleHotTiers = cfg.scaleHotTiers !== false;
    const apps = parseGamePolicy(gameXml);
    const { tables: limits, order } = parseLimitTables(perfXml);
    const updates = {}; // Type -> id -> new triple
    const changes = [];
    const seen = new Set();

    for (const app of apps) {
      app.modes.forEach((tiers, modeIndex) => {
        const modeName = MODES[modeIndex];
        const modeCfg = (cfg.modes && cfg.modes[modeName]) || {};
        if (!tiers.length) return;

        // ids[position] maps to the Type at the same position (TempLevel excluded)
        order.forEach((typeName, pos) => {
          let newBase;
          if (typeName === 'GPU') {
            newBase = [
              isSet(modeCfg.gpuMaxMhz) ? gpuLevelForMhz(tables.GPU, Number(modeCfg.gpuMaxMhz)) : null,
              isSet(modeCfg.gpuMinMhz) ? gpuLevelForMhz(tables.GPU, Number(modeCfg.gpuMinMhz)) : null,
            ];
          } else {
            const prefix = Object.keys(CPU_FIELDS).find((k) => CPU_FIELDS[k] === typeName);
            if (!prefix) return;
            const table = tables[typeName];
            newBase = [
              isSet(modeCfg[prefix + 'Max']) ? snapFloor(table, Number(modeCfg[prefix + 'Max'])) : null,
              isSet(modeCfg[prefix + 'Min']) ? snapFloor(table, Number(modeCfg[prefix + 'Min'])) : null,
            ];
          }
          const lock = modeCfg.lock === true;
          if (!lock && newBase[0] === null && newBase[1] === null) return;

          const baseId = tiers[0].ids[pos];
          const stockBase = limits[typeName] && limits[typeName][baseId];
          if (!stockBase) return;

          const tierTriple = (stock, isBaseTier) => (typeName === 'GPU'
            ? scaleGpu(stock, stockBase, newBase, tables.GPU.length - 1, scaleHotTiers, isBaseTier)
            : scaleCpu(stock, stockBase, newBase, tables[typeName], scaleHotTiers, isBaseTier));
          // Locked: every hotter tier reuses the coolest tier's limits, so ZUI never
          // steps down on temperature. Kernel thermal trips still apply.
          const lockedTriple = lock ? tierTriple(stockBase, true) : null;

          tiers.forEach((tier, tierIndex) => {
            const id = tier.ids[pos];
            const key = typeName + ':' + id;
            if (seen.has(key)) return;
            const stock = limits[typeName][id];
            if (!stock) return;
            seen.add(key);
            const next = lock && tierIndex > 0 ? lockedTriple.slice() : tierTriple(stock, tierIndex === 0);
            if (next.join('_') !== stock.join('_')) {
              (updates[typeName] = updates[typeName] || {})[id] = next;
              changes.push({ pkg: app.pkg, mode: modeName, tier: tierIndex, temp: tier.temp, type: typeName, id, from: stock, to: next });
            }
          });
        });
      });
    }

    const version = resolveVersion(cfg.version);
    let currentType = null;
    const lines = perfXml.split('\n').map((line) => {
      const typeMatch = /<Type name\s*=\s*"([^"]+)">/.exec(line);
      if (typeMatch) currentType = typeMatch[1];
      if (/<\/Type>/.test(line)) {
        currentType = null;
        return line;
      }
      const freq = /^(\s*<Freq level\s*=\s*")([^"]+)(">)([^<]*)(<\/Freq>.*)$/.exec(line);
      if (freq && currentType && updates[currentType] && updates[currentType][freq[2]]) {
        return freq[1] + freq[2] + freq[3] + updates[currentType][freq[2]].join('_') + freq[5];
      }
      return line;
    });

    let xml = lines.join('\n');
    xml = xml.replace(/(<PerformanceConfig\b[^>]*\bversion\s*=\s*")[^"]*(")/, '$1' + version + '$2');
    xml = xml.replace(/(<\?xml[^>]*\?>)/, '$1\n<!-- ' + GENERATED_MARKER + ' -->');

    // Beast memory boost needs both files: the perflock items and the per-game reference.
    let outGameXml = null;
    let boostedGames = 0;
    if (cfg.modes && cfg.modes.beast && cfg.modes.beast.memBoost === true) {
      if (!/<\/PerformanceSpecialList>/.test(xml)) throw new Error('PerformanceSpecialList section not found');
      xml = xml.replace(/(\n\s*<\/PerformanceSpecialList>)/, '\n' + specialItemsXml() + '$1');
      const game = rewriteGamePolicy(gameXml, version);
      outGameXml = game.xml;
      boostedGames = game.changed;
    }

    return {
      xml,
      gameXml: outGameXml,
      version,
      changes,
      stats: { apps: apps.length, changed: changes.length, boostedGames },
    };
  }

  return {
    MODES, DEFAULT_TABLES, CPU_FIELDS, GENERATED_MARKER, BEAST_BOOST_ITEM, RELEASE_ITEM,
    parseGamePolicy, parseLimitTables, detectTables, snapFloor, generate,
  };
});
